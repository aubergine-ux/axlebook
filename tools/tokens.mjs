// Generates apps/web/src/theme/tokens.css from logo-assets/tokens.json (the brand kit)
// and checks WCAG contrast for the colour pairs the UI relies on.
// Usage: node tools/tokens.mjs        (exits 1 if a pair falls below its minimum)
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const kit = JSON.parse(fs.readFileSync(path.join(root, 'logo-assets/tokens.json'), 'utf8'));
const out = path.join(root, 'apps/web/src/theme/tokens.css');

// ── Resolve colour tokens per theme ("{name}" references allowed) ───────────────
const raw = Object.fromEntries(kit.color.tokens.map((t) => [t.name, t.value]));
function resolve(name, theme, seen = new Set()) {
  if (seen.has(name)) throw new Error(`token cycle at ${name}`);
  seen.add(name);
  let v = raw[name];
  if (v === undefined) throw new Error(`unknown token ${name}`);
  if (typeof v === 'object') v = v[theme];
  const ref = /^\{(.+)\}$/.exec(v);
  return ref ? resolve(ref[1], theme, seen) : v;
}
const themes = kit.color.themes.map((t) => t.id);
const colors = Object.fromEntries(
  themes.map((th) => [th, Object.fromEntries(Object.keys(raw).map((n) => [n, resolve(n, th)]))]),
);

// ── Contrast checks ─────────────────────────────────────────────────────────
const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (hex) => {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => lin(Number.parseInt(h.slice(i, i + 2), 16) / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};
const SURFACES = ['surface', 'surface-raised', 'surface-sunken'];
const PAIRS = [
  ...SURFACES.flatMap((s) => [
    ['ink', s, 4.5],
    ['ink-muted', s, 4.5],
    ['line-strong', s, 3],
    ['focus', s, 3],
  ]),
  ...['surface', 'surface-raised'].flatMap((s) => [
    ['orange-text', s, 4.5],
    ['yellow', s, 4.5],
    ['red', s, 4.5],
  ]),
  ['orange-text', 'orange-soft', 4.5],
  ['yellow', 'yellow-soft', 4.5],
  ['red', 'red-soft', 4.5],
  ['on-orange', 'orange', 4.5],
  ['on-orange', 'orange-strong', 4.5],
  ['on-red', 'red', 4.5],
  ['on-readout', 'readout', 4.5],
  ['on-graphite', 'graphite', 4.5],
];
let failed = 0;
for (const th of themes) {
  for (const [fg, bg, min] of PAIRS) {
    const r = ratio(colors[th][fg], colors[th][bg]);
    if (r < min) {
      failed++;
      console.log(`FAIL ${th}: ${fg} on ${bg} = ${r.toFixed(2)} (needs ${min})`);
    }
  }
}

// ── Emit CSS ──────────────────────────────────────────────────────────────────
const themed = (group) =>
  Object.fromEntries(
    themes.map((th) => [
      th,
      Object.fromEntries(
        group.map((t) => [t.name, typeof t.value === 'object' ? t.value[th] : t.value]),
      ),
    ]),
  );
const shadows = themed(kit.shadow.tokens);
const decl = (obj, indent = '  ') =>
  Object.entries(obj)
    .map(([k, v]) => `${indent}--${k}: ${v};`)
    .join('\n');
const themeBlock = (th, indent) => `${decl(colors[th], indent)}\n${decl(shadows[th], indent)}`;

const fonts = kit.type.fonts
  .map(
    (f) => `@font-face {
  font-family: '${f.family}';
  src: url('/brand/${f.file}') format('woff2');
  font-weight: ${f.weight};
  font-style: normal;
  font-display: swap;${f.family === 'Archivo' ? '\n  font-stretch: 62% 125%;' : ''}
}`,
  )
  .join('\n\n');

// Token names are kept exactly as in the kit (--surface, --ink, --focus, --radius-md, …).
// Light lives on :root, dark on [data-theme="dark"]; the app always sets data-theme
// (resolving "system" itself), so no media query is needed here.
const css = `/* Generated by tools/tokens.mjs from logo-assets/tokens.json. Do not edit by hand. */

${fonts}

:root {
  --font-sans: ${kit.type.families.sans};
  --font-mono: ${kit.type.families.mono};
${decl(Object.fromEntries(kit.spacing.tokens.map((t) => [t.name, t.value])))}
${decl(Object.fromEntries(kit.radius.tokens.map((t) => [t.name, t.value])))}
  color-scheme: light;
${themeBlock('light', '  ')}
}

[data-theme='dark'] {
  color-scheme: dark;
${themeBlock('dark', '  ')}
}
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, css);
console.log(
  `wrote ${path.relative(root, out)} (${PAIRS.length * themes.length} contrast checks, ${failed} failed)`,
);
if (failed) process.exit(1);
