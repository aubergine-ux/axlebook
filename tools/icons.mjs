// Generates apps/web/src/components/icons.gen.ts from the brand kit's product icons
// (logo-assets/icons/svg/*.svg: 24px grid, 2px round strokes, currentColor).
// Usage: node tools/icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'logo-assets/icons/svg');
const out = path.join(root, 'apps/web/src/components/icons.gen.ts');

const icons = {};
for (const file of fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.svg'))
  .sort()) {
  const svg = fs.readFileSync(path.join(dir, file), 'utf8');
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(`${file}: expected a 24×24 viewBox`);
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const paths = [...inner.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)].map((m) => m[1]);
  const leftover = inner.replace(/<path\s+d="[^"]+"\s*\/>/g, '').trim();
  if (leftover)
    throw new Error(
      `${file}: unsupported markup (only <path d> is handled): ${leftover.slice(0, 60)}`,
    );
  icons[path.basename(file, '.svg')] = paths;
}

const body = Object.entries(icons)
  .map(
    ([name, paths]) =>
      `  ${/^[a-z]+$/.test(name) ? name : `'${name}'`}: [${paths.map((d) => `'${d}'`).join(', ')}],`,
  )
  .join('\n');
fs.writeFileSync(
  out,
  `// Generated by tools/icons.mjs from logo-assets/icons/svg. Do not edit by hand.\n\nexport const ICON_PATHS = {\n${body}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`wrote ${path.relative(root, out)} (${Object.keys(icons).length} icons)`);
